import sys; sys.path.insert(0, '.')
from ortak import *
with sync_playwright() as pw:
    o = Oturum(pw); o.ctx.grant_permissions(['camera', 'geolocation']); p = o.ac()
    p.click('text=Başla'); p.wait_for_timeout(600)
    p.click('#uygulama .btn.ana:has-text("Kıyafet ekle")'); p.wait_for_timeout(500)
    p.click('.sayfa.acik button.satir:has-text("Fotoğraf çek")'); p.wait_for_timeout(2500)
    o.ekran('60_kamera')
    ok(p.locator('.kam.acik').count() == 1 and not p.locator('.kam .kam-deklansor').is_disabled(), 'tam ekran kamera açıldı, deklanşör hazır')
    ok(p.locator('.kam .kam-izgara').is_visible() and p.locator('.kam-modlar button').count() == 2, 'ızgara ve Kıyafet/Boydan modları')
    p.click('.kam .kam-deklansor'); p.wait_for_timeout(500)
    p.click('.kam .kam-deklansor'); p.wait_for_timeout(500)
    ok(p.locator('.kam .kam-adet').inner_text() == '2' and 'Bitti (2)' in p.inner_text('.kam .kam-bitti'), 'art arda iki fotoğraf çekildi')
    p.locator('.kam .kam-ust-sag .kam-btn').nth(1).click(); p.wait_for_timeout(150)
    ok('3s' in p.inner_text('.kam .kam-ust-sag'), 'zamanlayıcı 3 sn')
    p.locator('.kam-modlar button', has_text='Boydan').click(); p.wait_for_timeout(1500)
    ok('10s' in p.inner_text('.kam .kam-ust-sag') and 'yasla' in p.inner_text('.kam .kam-ipucu'), 'Boydan modu: 10 sn zamanlayıcı ve ipucu')
    o.ekran('61_kamera_boydan')
    p.click('.kam .kam-bitti'); p.wait_for_selector('.sayfa.acik .buyuk-resim', timeout=15000)
    ok(p.locator('.kam').count() == 0, 'Bitti: kamera kapandı, çekilenler sırayla düzenlemeye geldi')
    p.locator('.sayfa.acik .alt-bar .btn.ikincil').click(); p.wait_for_timeout(900)
    p.wait_for_selector('.sayfa.acik .buyuk-resim', timeout=15000)
    ok(p.locator('.sayfa.acik .buyuk-resim').count() == 1, 'ikinci fotoğraf da sırayla geldi')
    print([h for h in o.hatalar if 'analiz' not in h])
    o.kapat()
ozet()
