import sys, os, json; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ortak import *
# Elle kırpma, arka planı silinen parçanın boyutu, yıllık PRO planı
KOK = os.path.dirname(os.path.abspath(__file__))
_ust = open(os.path.join(KOK, 'parcasec.py')).read().split('with sync_playwright')[0]
exec(_ust[:_ust.index('SAY = ')] if 'SAY = ' in _ust else _ust.split('def ac_sayfa')[0])
SAHTE = SAHTE.replace("odemeSorgula: (req) => yanit(req, {ok: true, products: []}), odemeAl: (req) => yanit(req, {ok: false}),",
  "odemeSorgula: (req, ids) => yanit(req, {ok: true, products: [{id: 'kombinle_pro_aylik', price: '$14.99'}, {id: 'kombinle_pro_yillik', price: '$99.99'}, {id: 'jeton_50', price: '$2.49'}]}), odemeAl: (req, id) => { window.__alinan = id; yanit(req, {ok: false}); }, odemeHazir: () => true,")
BOYUT = """() => new Promise(r => { const i = document.querySelector('.sayfa.acik .buyuk-resim'); const f = () => r([i.naturalWidth, i.naturalHeight]); i.complete && i.naturalWidth ? f() : i.onload = f; })"""

def son(p):
    return p.locator('.sayfa.acik').last

with sync_playwright() as pw:
    o = Oturum(pw, hava=met_yanit(taban=14)); o.ctx.add_init_script(SAHTE); p = o.ac()
    p.click('text=Başla'); p.wait_for_timeout(800)
    p.evaluate("window.__mod.tekParca = true")
    print('— Yeni parçada elle kırpma')
    p.set_input_files('#dosyaSec', [os.path.join(KOK, 'foto', 'kazak_krem.jpg')])
    p.wait_for_selector('.sayfa.acik .buyuk-resim', timeout=20000); p.wait_for_timeout(500)
    once = p.evaluate(BOYUT)
    ok(son(p).locator('button', has_text='Kırp').count() == 1, 'düzenleme ekranında "Kırp" düğmesi')
    son(p).locator('button', has_text='Kırp').click(); p.wait_for_selector('.sayfa.acik .kirp-kutu'); p.wait_for_timeout(400)
    o.ekran('k1_kirp')
    kb = son(p).locator('.kirp-kutu').bounding_box()
    tut = son(p).locator('.kirp-tut.sag-alt').bounding_box()
    p.mouse.move(tut['x'] + tut['width'] / 2, tut['y'] + tut['height'] / 2); p.mouse.down()
    p.mouse.move(tut['x'] - kb['width'] * 0.45, tut['y'] - kb['height'] * 0.2, steps=8); p.mouse.up(); p.wait_for_timeout(200)
    kb2 = son(p).locator('.kirp-kutu').bounding_box()
    ok(kb2['width'] < kb['width'] * 0.7 and kb2['height'] < kb['height'] * 0.9, 'köşeden tutunca çerçeve küçüldü')
    m = son(p).locator('.kirp-kutu').bounding_box()
    p.mouse.move(m['x'] + m['width'] / 2, m['y'] + m['height'] / 2); p.mouse.down(); p.mouse.move(m['x'] + m['width'] / 2 + 40, m['y'] + m['height'] / 2 + 20, steps=5); p.mouse.up()
    m2 = son(p).locator('.kirp-kutu').bounding_box()
    ok(abs(m2['width'] - m['width']) < 2 and m2['x'] > m['x'] + 20, 'çerçeve içinden sürükleyince taşındı')
    son(p).locator('.alt-bar .btn.ana').click(); p.wait_for_timeout(1200)
    sonra = p.evaluate(BOYUT)
    ok(sonra[0] < once[0] * 0.8 and abs(sonra[0] / sonra[1] - m2['width'] / m2['height']) < 0.08, 'fotoğraf seçilen çerçeveye göre kırpıldı: %s → %s' % (once, sonra))
    ok('kırpıldı' in p.inner_text('#tost'), 'kırpıldı bildirimi')
    son(p).locator('.alt-bar .btn.ana').click(); p.wait_for_timeout(900)
    print('— Kayıtlı parçada kırpma')
    p.click('nav.alt-menu button[data-sekme="dolap"]'); p.wait_for_timeout(900)
    p.locator('.g-giysi').first.click(); p.wait_for_selector('.sayfa.acik .buyuk-resim'); p.wait_for_timeout(600)
    once = p.evaluate(BOYUT)
    son(p).locator('button', has_text='Kırp').click(); p.wait_for_selector('.sayfa.acik .kirp-kutu'); p.wait_for_timeout(300)
    son(p).locator('.alt-bar .btn.ana').click(); p.wait_for_timeout(1500)
    sonra = p.evaluate(BOYUT)
    ok(sonra != once and sonra[0] < once[0], 'kayıtlı parçanın fotoğrafı kırpılıp saklandı: %s → %s' % (once, sonra))
    son(p).locator('.bas .ikon-btn').click(); p.wait_for_timeout(500)
    print('— Arka planı silinen parça küçülmesin')
    from PIL import Image as _I, ImageDraw as _D
    yol = os.path.join(EKRAN, '_kucuk_parca.jpg'); im = _I.new('RGB', (1000, 1000), (255, 255, 255)); _D.Draw(im).rectangle([420, 350, 580, 650], fill=(122, 35, 64)); im.save(yol, quality=95)
    p.set_input_files('#dosyaSec', [yol]); p.wait_for_selector('.sayfa.acik .buyuk-resim', timeout=20000); p.wait_for_timeout(500)
    son(p).locator('button', has_text='Arka planı sil').click(); p.wait_for_timeout(2500)
    r = p.evaluate(BOYUT)
    ok(max(r) >= 760 and abs(r[1] / r[0] - 300 / 160) < 0.2, 'küçük parça kesildikten sonra büyütüldü ve çerçeveyi dolduruyor: %s' % (r,))
    son(p).locator('.bas .ikon-btn').click(); p.wait_for_timeout(500)
    print('— Yıllık PRO')
    p.evaluate("magazaSayfasi()") if False else p.click('#jetonHap'); p.wait_for_timeout(900)
    s = son(p)
    ok(s.locator('.g-pro-plan button').count() == 2 and s.locator('.g-pro-plan button[aria-pressed="true"]').inner_text() == 'Yıllık', 'mağazada yıllık/aylık seçimi, yıllık seçili')
    ok('$99.99' in s.locator('.g-pro-fiyat').inner_text() and '/yıl' in s.locator('.g-pro-fiyat').inner_text() and 'yıllık' in s.locator('.g-pro h4').inner_text(), 'yıllık fiyat Play\'den: ' + s.locator('.g-pro-fiyat').inner_text())
    o.ekran('k2_yillik')
    s.locator('.g-pro-btn').click(); p.wait_for_timeout(500)
    ok(p.evaluate('window.__alinan') == 'kombinle_pro_yillik', 'yıllık abonelik satın alma isteği')
    s.locator('.g-pro-plan button', has_text='Aylık').click(); p.wait_for_timeout(200)
    ok('$14.99' in s.locator('.g-pro-fiyat').inner_text() and '/ay' in s.locator('.g-pro-fiyat').inner_text(), 'aylık fiyat')
    s.locator('.g-pro-btn').click(); p.wait_for_timeout(500)
    ok(p.evaluate('window.__alinan') == 'kombinle_pro_aylik', 'aylık abonelik satın alma isteği')
    ok(not [h for h in o.hatalar if 'pageerror' in h], 'sayfa hatası yok: ' + str(o.hatalar[:2]))
    o.kapat()
ozet()
