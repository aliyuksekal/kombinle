def kur(p, ad):
    p.click('.g-arac:has-text("Kombin kur")'); p.wait_for_timeout(450)
    if p.locator('.sayfa.acik .g-magaza').count(): return False
    for slot in ['Üst', 'Alt', 'Ayakkabı']:
        p.locator('.sayfa.acik .slot', has_text=slot).first.click(); p.wait_for_timeout(400)
        p.locator('.sayfa.acik .secim-izgara .oge').first.click(); p.wait_for_timeout(400)
    p.fill('.sayfa.acik input.metin', ad)
    p.locator('.sayfa.acik .cip', has_text='İş / toplantı').first.click(); p.wait_for_timeout(150)
    p.click('.sayfa.acik .alt-bar .btn.ana'); p.wait_for_timeout(500)
    return True

